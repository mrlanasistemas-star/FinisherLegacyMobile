import { apiClient } from '@/api/client';
import { toAppError } from '@/api/errors';
import type { Order } from '@/types/models';

/**
 * Contact + delivery the buyer chose. Every field is optional for the
 * server (it defaults to the account's name/email and "pickup"); amounts are
 * never sent — shipping is priced and frozen server-side.
 */
export interface CheckoutPayload {
  delivery_method: 'pickup' | 'shipping';
  phone?: string;
  address_line?: string;
  address_neighborhood?: string;
  address_city?: string;
  address_state?: string;
  address_postal_code?: string;
  notes?: string;
}

/**
 * `POST /checkout` recalculates price/stock/totals server-side and creates
 * the Order — the cart is never authoritative. `idempotencyKey` must be
 * generated by the caller BEFORE the first attempt (uuidv4()) and reused on
 * every retry of the same checkout attempt, so a network timeout can never
 * create two orders. The server only remembers successful responses, so a
 * 422 can be fixed and retried; the caller still mints a new key whenever
 * the payload changes.
 */
export async function checkout(idempotencyKey: string, payload?: CheckoutPayload): Promise<Order> {
  try {
    const { data } = await apiClient.post<{ data: Order }>('checkout', payload ?? {}, {
      headers: { 'Idempotency-Key': idempotencyKey },
    });
    return data.data;
  } catch (error) {
    throw toAppError(error);
  }
}
